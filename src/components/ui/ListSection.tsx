import type { ReactNode } from 'react';
import { useId } from 'react';
import { classNames } from './class-names';
import { Heading } from './Heading';

/*
 * `ListSection` — a heading plus the list it names.
 *
 * The heading is a real `<h2>` (through `Heading`, so the level cannot be
 * skipped from the screen's `h1`), not a styled `div`: VoiceOver's heading rotor
 * can then jump from section to section, and the `<section>` is named by it with
 * `aria-labelledby`, so a screen reader announces which group a row belongs to
 * rather than reading an undifferentiated run of rows.
 *
 * The id is generated by React's `useId`, which keeps it unique per instance
 * without a module-level counter or a required prop at every call site.
 */

export type ListSectionProps = {
  /** Section title; the section is labelled by it. */
  header: string;
  children: ReactNode;
  className?: string;
};

export function ListSection({ header, children, className }: ListSectionProps) {
  const headerId = useId();

  return (
    <section
      aria-labelledby={headerId}
      className={classNames('bs-list-section', className)}
    >
      <Heading
        className="bs-list-section__header"
        id={headerId}
        variant="section-header"
      >
        {header}
      </Heading>
      {children}
    </section>
  );
}
