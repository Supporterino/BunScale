import { createHashHistory, createRouter } from '@tanstack/react-router';
import { queryClient } from './lib/query-client';
import { routeTree } from './routeTree.gen';

/*
 * The app's single router instance. It is created here, at module scope, and
 * imported by `src/main.tsx`, so there is one router for the lifetime of the
 * window and the `Register` declaration below is the one TypeScript sees.
 *
 * `createHashHistory` rather than browser history is deliberate and is a
 * `tanstack-router-conventions` rule: Tauri serves the built frontend as static
 * assets over its own protocol, where a reload or a deep link on a real path
 * (`/settings`) has no server-side fallback to `index.html` and would fail to
 * load. Hash history keeps every route reachable inside `index.html`. One route
 * tree serves both form factors (iOS and macOS) — layouts adapt, routes do not
 * fork.
 *
 * `routeTree.gen.ts` is generated by the router plugin from `src/routes/**`
 * (never hand-edited) and is committed, so the drift check the gate runs against
 * it is meaningful rather than vacuous (TOOL-4).
 *
 * `context` carries the query cache the same way the provider does, which is
 * what lets a route's `loader` prefetch through it instead of reaching for a
 * module singleton (`tanstack-router-conventions`, "Setup" and "Data").
 */
export const router = createRouter({
  routeTree,
  history: createHashHistory(),
  context: { queryClient },
});

/*
 * Registers this instance's route types globally, which is what makes `to`,
 * `params` and `search` type-checked at every `Link`, `useNavigate` and
 * `redirect` call site — the reason the conventions forbid string-built URLs.
 */
declare module '@tanstack/react-router' {
  interface Register {
    router: typeof router;
  }
}
